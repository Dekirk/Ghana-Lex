import { NextRequest, NextResponse } from "next/server";
import ZAI from "z-ai-web-dev-sdk";
import { db } from "@/lib/db";
import type { AiAnswer } from "@/lib/types";

// Ghanaian legal-research AI endpoint.
// Returns an answer plus a verified/unverified badge. The verification logic
// looks for canonical Ghanaian citation tokens — Act numbers, NRCD/SMCD/AFRC
// decree references, [YYYY-YYYY] SCGLR/HGLR citations, or article+section
// pairings — which usually indicate a statute-grounded answer.

const GHANA_CITATION_PATTERNS = [
  /\bAct\s+\d{1,4}\b/i,
  /\bNRCD\s+\d{1,4}\b/i,
  /\bSMCD\s+\d{1,4}\b/i,
  /\bAFRC\s+\d{1,4}\b/i,
  /\bPNDCL\s+\d{1,4}\b/i,
  /\bLI\s+\d{1,4}\b/i,
  /\b\d{4}\s*-\s*\d{4}\s*SCGLR\b/i,
  /\b\d{4}\s*-\s*\d{4}\s*HGLR\b/i,
  /\bSection\s+\d+/i,
  /\bArticle\s+\d+/i,
  /\bOrder\s+\d+/i,
  /\bRule\s+\d+/i,
  /\bv\.\s+/i, // "v." party citations
];

const DISCLAIMER =
  "This answer is generated by GhanaLex AI for general legal-research purposes only. It is not legal advice. Always confirm against the authoritative source and consult a qualified legal practitioner before relying on it.";

const SYSTEM_PROMPT = `You are GhanaLex AI, a legal-research assistant specialising in the law of the Republic of Ghana — including the 1992 Constitution, Acts of Parliament, NRCD/SMCD/PNDCL decrees, subsidiary instruments, the High Court (Civil Procedure) Rules (C.I. 47), Court of Appeal Rules (C.I. 19) and Supreme Court Rules (C.I. 16), the Evidence Act 1975 (NRCD 323), the ADR Act 2010 (Act 798), and Ghanaian case law as reported in SCGLR, HGLR and GMK.

When answering:
1. State the position under Ghanaian law plainly and accurately.
2. Cite the statute, instrument or case authority in standard Ghanaian form (e.g. "Section 12 of the Limitation Decree, 1972 (NRCD 54)" or "Mensah v. Aryee [2009-2010] SCGLR 762").
3. Where the question is about procedure, identify the court and the rule that governs it.
4. Where Ghanaian authority is unavailable or uncertain, say so explicitly and outline the closest common-law analogue.
5. Be neutral and do not give personal advice on whether a litigant should sue or settle.
6. Keep answers under 220 words. No headings, no markdown, no preamble.`;

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const question: string = (body?.question ?? "").toString().trim();
    if (!question || question.length < 5) {
      return NextResponse.json(
        { error: "Please enter a question of at least 5 characters." },
        { status: 400 },
      );
    }

    let answerText = "";
    let sources = "";

    // Try the live LLM via z-ai-web-dev-sdk.
    try {
      const zai = await ZAI.create();
      const completion = await zai.chat.completions.create({
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          { role: "user", content: question },
        ],
        thinking: { type: "disabled" },
      });
      answerText =
        completion?.choices?.[0]?.message?.content?.trim() ??
        completion?.choices?.[0]?.text?.trim() ??
        "";
    } catch (llmErr) {
      console.error("[ai-search] LLM call failed:", llmErr);
      answerText = "";
    }

    // Fallback to verified answers already in our knowledge base (AiQuery rows).
    if (!answerText) {
      const prior = await db.aiQuery.findFirst({
        where: { verified: true, question: { contains: question } },
        orderBy: { createdAt: "desc" },
      });
      if (prior) {
        answerText = prior.answer;
        sources = prior.sources ?? "";
      } else {
        answerText =
          "GhanaLex AI could not reach its reasoning engine for this query. This is a temporary technical issue — please retry in a moment. In the meantime, you may consult the Laws of Ghana (GhanaPub), the Ghana Law Reports (SCGLR) or your chamber's library.";
      }
    }

    // Verification — does the answer carry a real Ghanaian citation?
    const verified = GHANA_CITATION_PATTERNS.some((p) => p.test(answerText));

    // Extract any "Sources:" trailing line so we can render them separately.
    const sourceMatch = answerText.match(
      /Sources?:\s*([^\n]+)$/i,
    );
    if (sourceMatch) {
      sources = sources || sourceMatch[1];
      answerText = answerText.replace(/Sources?:\s*[^\n]+$/i, "").trim();
    }

    // Persist the query for the public history feed.
    const saved = await db.aiQuery.create({
      data: {
        question,
        answer: answerText,
        verified,
        sources: sources || null,
      },
    });

    const payload: AiAnswer = {
      question,
      answer: answerText,
      verified,
      sources: sources || null,
      disclaimer: DISCLAIMER,
      createdAt: saved.createdAt.toISOString(),
    };

    return NextResponse.json(payload);
  } catch (err) {
    console.error("[ai-search] fatal:", err);
    return NextResponse.json(
      { error: "The AI search service encountered an unexpected error." },
      { status: 500 },
    );
  }
}

export async function GET() {
  // Public feed of recent AI queries.
  const recent = await db.aiQuery.findMany({
    orderBy: { createdAt: "desc" },
    take: 12,
  });
  return NextResponse.json({
    items: recent.map((q) => ({
      question: q.question,
      answer: q.answer,
      verified: q.verified,
      sources: q.sources,
      createdAt: q.createdAt.toISOString(),
      disclaimer:
        "AI-generated answer for legal research only — verify against authoritative sources before relying on it.",
    })),
  });
}
